import assert from 'node:assert/strict'
const { default: puppeteer } = await import(process.env.PUPPETEER_CORE || 'puppeteer-core')
const base = process.env.LANDING_URL || 'http://127.0.0.1:5195'
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_BIN || '/usr/bin/chromium', headless:true, args:['--no-sandbox','--use-angle=swiftshader','--use-gl=angle','--enable-unsafe-swiftshader'], defaultViewport:{width:1440,height:1050} })
const page = await browser.newPage(), errors=[], requests=[]
page.on('pageerror', e=>errors.push(e.message)); page.on('request', r=>requests.push(r.url()))
page.setDefaultTimeout(60000)
const check=(value,label)=>{assert.ok(value,label);console.log('PASS',label)}
try {
  await page.goto(`${base}/?lang=zh-CN`,{waitUntil:'networkidle0'})
  check(!await page.$('.book-scene canvas'), 'hero loads without initializing the 3D scene')
  await page.click('.landing-nav-links a[href="#experience"]')
  await page.waitForSelector('.book-story[data-ready] canvas')
  await page.evaluate(()=>document.fonts.ready)
  const modelFrame = () => page.screenshot()
  const progress = async value => {
    await page.evaluate(value => {
      const story=document.querySelector('.book-story'), scroller=document.querySelector('.landing')
      scroller.scrollTo({top:story.getBoundingClientRect().top+scroller.scrollTop+value*(story.offsetHeight-scroller.clientHeight),behavior:'instant'})
    },value)
    await page.waitForFunction(value=>Math.abs(Number(document.querySelector('.book-story').dataset.progress)-value)<.002,{},value)
  }
  check(await page.$eval('h1',e=>e.textContent.includes('阅读之中')), 'Chinese landing renders at public root')
  check(!requests.some(url=>url.includes('/api/')||url.includes('/App.tsx')||url.includes('/engine/scene')), 'showcase does not initialize sessions or the interactive reader')
  check(!await page.$('.landing-reader-image'), 'old screenshot preview is replaced by a real canvas')
  check(await page.$eval('.book-story-copy h2',e=>e.textContent.includes('翻开一本书')), 'new story copy is translated')
  await progress(0); await page.screenshot({path:'/tmp/landing-story-cover.png'})
  await new Promise(resolve=>setTimeout(resolve,600))
  const closed=await modelFrame()
  await progress(.065)
  const opened=await modelFrame()
  check(!closed.equals(opened), 'scrolling changes the rendered book geometry')
  const featureCount = await page.$$eval('.book-chapters option', options=>options.length)
  check(featureCount===10, 'all ten features are reachable in the chapter selector')
  check(await page.$eval('.book-chapters button:first-child',e=>e.disabled), 'previous is disabled at the first chapter')
  for(let i=0;i<featureCount;i++) {
    await progress((i+.65)/featureCount)
    check(await page.$eval('.book-story', (e,i)=>e.dataset.phase===String(i),i), `chapter ${i+1} follows the shared timeline`)
  }
  check(await page.$eval('.book-chapters button:last-child',e=>e.disabled), 'next is disabled at the last chapter')
  await progress(.118)
  await page.waitForFunction(()=>document.querySelector('.story-angle strong').textContent==='0°')
  await progress(.178)
  await page.waitForFunction(()=>document.querySelector('.story-angle strong').textContent==='62°')
  check(await page.$eval('.book-story',e=>Number(e.style.getPropertyValue('--tilt-demo'))>.999), 'view readout and slider follow the reader pitch range, from 0 to 62 degrees')
  await progress(.165)
  check(!(await modelFrame()).equals(opened), 'perspective chapter changes the book pose')
  await progress(.405)
  await page.waitForSelector('.story-markdown-output[data-markdown-step="0"]')
  check(await page.$eval('.story-markdown-output',e=>!e.querySelector('ul')&&e.textContent.includes('-')), 'Markdown keeps a lone minus literal')
  await progress(.435)
  check(await page.$$eval('.story-markdown-output li',e=>e.length===2), 'Markdown renders real list items')
  await progress(.465)
  check(!!await page.$('.story-markdown-output strong'), 'Markdown renders emphasis inline')
  check(await page.$eval('.book-story',e=>e.dataset.phase==='4'&&Number(e.style.getPropertyValue('--note'))>.99), 'note appears in the Markdown chapter')
  await page.screenshot({path:'/tmp/landing-story-notes.png'})
  await progress(.485)
  check(!!await page.$('.story-markdown-output blockquote'), 'Markdown renders a blockquote without a preview pane')
  await progress(.515)
  check(await page.$eval('.book-note-footer',e=>e.textContent.includes('正在保存')), 'save demonstration starts in progress')
  await progress(.565)
  check(await page.$eval('.book-note-footer',e=>e.textContent.includes('已保存')), 'save demonstration reaches its saved state')
  await progress(.785)
  check(await page.$eval('.book-story',e=>e.dataset.phase==='7'&&Number(e.style.getPropertyValue('--branch-2'))>.99), 'all mind-map branches unfold')
  await page.screenshot({path:'/tmp/landing-story-map.png'})
  await progress(.865)
  await page.waitForFunction(()=>performance.getEntriesByType('resource').some(e=>e.name.includes('/landing/earth.svg')))
  check(await page.$eval('.book-story',e=>Number(e.style.getPropertyValue('--atlas'))>.99), 'atlas chapter loads the globe texture on demand')
  check(!requests.some(url=>url.includes('/api/')), 'all ten demonstrations run without API or AI requests')
  await progress(0)
  await new Promise(resolve=>setTimeout(resolve,600))
  const reversed=await modelFrame()
  // Allow subpixel compositing / antialiasing differences, but not a changed pose.
  const reverseDifference = await page.evaluate(async (a,b) => {
    const pixels = async data => {
      const bitmap = await createImageBitmap(await (await fetch('data:image/png;base64,'+data)).blob())
      const canvas=document.createElement('canvas');canvas.width=bitmap.width;canvas.height=bitmap.height
      const ctx=canvas.getContext('2d');ctx.drawImage(bitmap,0,0);bitmap.close()
      return ctx.getImageData(0,0,canvas.width,canvas.height).data
    }
    const x=await pixels(a),y=await pixels(b)
    if(x.length!==y.length)return Infinity
    let difference=0;for(let i=0;i<x.length;i++)difference+=Math.abs(x[i]-y[i])
    return difference/x.length
  },closed.toString('base64'),reversed.toString('base64'))
  check(reverseDifference<.25, 'reverse scrolling restores the closed-book frame (mean pixel difference '+reverseDifference.toFixed(4)+')')
  await page.focus('.book-chapters button:last-child'); await page.keyboard.press('Enter')
  await page.waitForFunction(()=>document.querySelector('.book-story').dataset.phase==='1')
  check(true,'keyboard activation advances to the next chapter')
  await page.select('.book-chapters select','8')
  await page.waitForFunction(()=>document.querySelector('.book-story').dataset.phase==='8')
  check(true, 'chapter selector jumps directly to 3D maps')
  await page.click('.book-stage-top a')
  await page.waitForFunction(()=>document.querySelector('#possibilities').getBoundingClientRect().top<80)
  check(true,'skip link leaves the sticky sequence')
  await page.click('.landing-faq summary')
  check(await page.$eval('.landing-faq details',e=>e.open), 'FAQ disclosure opens')
  await page.select('.language-switch select','en')
  await page.evaluate(()=>document.fonts.ready)
  await progress(.2)
  await page.waitForSelector('.book-story[data-ready] canvas')
  check(await page.$eval('h1',e=>e.textContent.includes('A book opens.')), 'language switch translates landing in place')
  check(await page.$eval('.landing-text-link',e=>e.href.includes('sample=alice')&&e.href.includes('lang=en')), 'English sample link selects English book and locale')
  for(const locale of ['en','zh-CN']) {
    await page.select('.language-switch select',locale)
    for(const width of [390,320]) {
      await page.setViewport({width,height:844,deviceScaleFactor:2})
      check(await page.$eval('.landing',e=>e.scrollWidth<=e.clientWidth), `${locale} at ${width}px has no horizontal overflow`)
      check(await page.$eval('.landing-nav-actions',e=>e.getBoundingClientRect().right<=innerWidth), `${locale} at ${width}px keeps navigation reachable`)
      for(const value of Array.from({length:featureCount},(_,i)=>(i+.65)/featureCount)) {
        await progress(value)
        check(await page.$eval('.book-stage',e=>{const r=e.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth}), `${locale} chapter ${value} fits at ${width}px`)
        check(await page.$eval('.book-stage-bottom',e=>e.getBoundingClientRect().bottom<=innerHeight), 'chapter controls stay inside the viewport')
      }
    }
    await page.screenshot({path:`/tmp/landing-story-${locale}-mobile.png`})
  }
  await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}])
  await page.waitForSelector('.book-story[data-static]')
  check(!await page.$('.book-scene canvas')&&(await page.$$('.book-story-copy article[data-active]')).length===featureCount,'reduced motion disposes WebGL and exposes every feature')
  check(await page.$eval('.landing',e=>getComputedStyle(e).scrollBehavior==='auto'), 'reduced motion disables smooth scrolling')
  await page.setViewport({width:1440,height:1000,deviceScaleFactor:1})
  const fallback=await browser.newPage()
  await fallback.evaluateOnNewDocument(()=>{
    const original=HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext=function(type,...args){return String(type).startsWith('webgl')?null:original.call(this,type,...args)}
  })
  await fallback.goto(`${base}/?lang=en`,{waitUntil:'networkidle0'})
  await fallback.click('.landing-nav-links a[href="#experience"]')
  await fallback.waitForSelector('.book-story[data-static]')
  check((await fallback.$$('.book-story-copy article[data-active]')).length===featureCount&&!!await fallback.$('.book-poster'),'no-WebGL visitors get all ten features and a readable illustrated fallback')
  await fallback.close()
  await page.click('.landing-nav-enter')
  await page.waitForSelector('.shelf-heading')
  check(new URL(page.url()).pathname==='/shelf', 'shelf CTA opens the dedicated shelf route')
  await page.click('.shelf-home-link')
  await page.waitForSelector('.landing')
  check(new URL(page.url()).pathname==='/', 'shelf brand returns to landing')
  await page.click('.landing-text-link')
  await page.waitForFunction(()=>window.__reader?.hasBook&&!window.__store.getState().loading,{timeout:120000})
  check(new URL(page.url()).pathname.startsWith('/book/'), 'sample CTA opens a real reader book')
  await page.click('.shelf-up')
  await page.waitForSelector('.shelf-heading')
  check(new URL(page.url()).pathname==='/shelf', 'reader Back returns to shelf, not marketing home')
  await page.goBack()
  await page.waitForFunction(()=>window.__reader?.hasBook&&!window.__store.getState().loading,{timeout:120000})
  check(new URL(page.url()).pathname.startsWith('/book/'), 'browser Back reopens the book')
  await page.goBack()
  await page.waitForSelector('.landing')
  check(true,'browser Back returns from reader to public landing')
  check(errors.length===0,`no browser runtime errors: ${errors.join('; ')}`)
} finally {await browser.close()}
