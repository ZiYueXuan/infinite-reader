// Start a VITE_BACKEND=local Vite server. Uses isolated local sample books only.
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const { default: puppeteer } = await import(process.env.PUPPETEER_CORE || 'puppeteer-core')
const base = process.env.READER_ORIGIN || 'http://127.0.0.1:5198'
const output = process.env.SCREENSHOT_DIR || '/tmp/infinite-reader-phone'
await mkdir(output, { recursive: true })
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_BIN || '/usr/bin/chromium', headless: true })
const check = (value, label) => { assert.ok(value, label); console.log('PASS', label) }
const iphone = 'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 Version/18.0 Mobile/15E148 Safari/604.1'
const android = 'Mozilla/5.0 (Linux; Android 14; Pixel 8) AppleWebKit/537.36 Chrome/130.0.0.0 Mobile Safari/537.36'
const ready = p => p.waitForFunction(() => window.__reader?.hasBook && !window.__store.getState().loading, { timeout: 120000 })
const settle = p => p.evaluate(() => { __reader.advance(4); __reader.paused = false })
const jump = async (p, index) => {
  await p.evaluate(index => __reader.goToLeaf(index), index); await settle(p)
  await p.waitForFunction(() => Object.values(__reader.visiblePages).filter(index => index >= 0).every(index => __reader.tex.get(index).image.width > 4))
}
const position = p => p.evaluate(() => { const r = __reader, page = r.pagination.pages[r.visiblePages.right]; return { chapter: page.chapter, start: page.start, end: page.end, index: page.index } })
try {
  const page = await browser.newPage(), errors = [], api = []
  page.setDefaultTimeout(60000)
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) api.push(request.url()) })
  await page.emulate({ userAgent: iphone, viewport: { width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true } })
  await page.goto(`${base}/?sample=zh&lang=zh-CN`); await ready(page)
  check(await page.evaluate(() => __reader.phone && __reader.visiblePages.left === -1 && __reader.pagination.config.pageW === 390), 'phone opens one viewport-sized page')
  check(await page.evaluate(() => !__reader.pagination.pages.some(p => p.special === 'blank')), 'phone sequence contains no spread-padding pages')
  await jump(page, 2)
  await page.screenshot({ path: `${output}/reading.png` })
  const cdp = await page.createCDPSession()
  const touch = (type, x, y = 400, id = 1) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: /End|Cancel/.test(type) ? [] : [{ x, y, id }] })
  const swipe = async (from, to, cancel = false) => {
    await touch('touchStart', from)
    for (let i = 1; i <= 12; i++) { await touch('touchMove', from + (to - from) * i / 12); await new Promise(r => setTimeout(r, 18)) }
    await touch(cancel ? 'touchCancel' : 'touchEnd'); await settle(page)
  }
  await touch('touchStart', 350)
  for (let x = 340; x >= 230; x -= 10) { await touch('touchMove', x); await new Promise(r => setTimeout(r, 20)) }
  check(await page.evaluate(() => __reader.book.hasHeldLeaf && __reader.book.flyers[0].phi > .1 && __reader.book.flyers[0].phi < 2), 'touch drag holds a curved physical leaf')
  await page.screenshot({ path: `${output}/page-curl.png` })
  await touch('touchCancel'); await settle(page)
  check((await position(page)).index === 2, 'cancelled touch returns to the original page')
  await swipe(350, 60)
  check((await position(page)).index === 3, 'left swipe advances exactly one page')
  await swipe(50, 340)
  check((await position(page)).index === 2, 'right swipe restores the preceding page')
  await page.touchscreen.tap(195, 350)
  check(await page.$eval('.phone-controls', e => e.dataset.open === 'true'), 'center tap opens reading controls')
  await page.screenshot({ path: `${output}/controls.png` })
  await page.click('.phone-top button:last-child')
  check(await page.$eval('.phone-controls', e => e.dataset.open === 'false'), 'controls can be dismissed without changing pages')
  const at = await page.$eval('.text-page .w', e => { const r = e.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await touch('touchStart', at.x, at.y)
  await new Promise(r => setTimeout(r, 650)); await touch('touchEnd')
  await page.waitForSelector('.pop')
  check(await page.evaluate(() => !getSelection()?.toString() && __store.getState().popover?.kind === 'selection' && !!__store.getState().popover.text), 'long press selects source text without a browser-native range')
  check(await page.$eval('.pop', e => { const r = e.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth }), 'selection actions fit the phone width')
  await page.screenshot({ path: `${output}/selection.png` })
  await page.click('.pop button[aria-label="添加行内笔记"]')
  await page.waitForSelector('.note-rich-content', { visible: true })
  await page.focus('.note-rich-content'); await page.keyboard.sendCharacter('手机阅读批注')
  await page.click('[data-note-done]')
  await page.waitForFunction(() => !__store.getState().editingNote && __reader.pagination.pages.some(p => p.notes?.some(n => n.lines.some(l => l.words.map(w => w.text).join('').includes('手机阅读批注')))))
  check(true, 'inline note editing and reflow work on phone pages')
  await page.evaluate(() => { __reader.clearSelection(); __store.getState().setPopover(null) })
  const beforeRotation = await position(page)
  await page.setViewport({ width: 844, height: 390, deviceScaleFactor: 2, isMobile: true, hasTouch: true, isLandscape: true })
  await page.waitForFunction(() => __reader.pagination.config.pageW === 844)
  const rotated = await position(page)
  check(rotated.chapter === beforeRotation.chapter && rotated.start <= beforeRotation.start && rotated.end >= beforeRotation.start, 'rotation preserves the source passage')
  await page.screenshot({ path: `${output}/landscape.png` })
  await page.setViewport({ width: 320, height: 568, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
  await page.waitForFunction(() => __reader.pagination.config.pageW === 320)
  check(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth && __reader.visiblePages.left === -1), '320px phone remains a single page without horizontal overflow')
  await page.click('.phone-folio')
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.phone-bottom')).transform === 'none')
  await page.click('.phone-bottom nav button:last-child')
  await page.waitForSelector('.phone-settings', { visible: true })
  await page.click('.phone-type-size button:last-child')
  await page.waitForFunction(() => __reader.pagination.config.fontSize === 21)
  check(true, 'text size changes repaginate the phone page')
  await page.screenshot({ path: `${output}/settings-320.png` })
  await jump(page, 5)
  await page.evaluate(() => __store.getState().saveReadingProgress())
  const beforeReload = await position(page)
  await page.reload(); await ready(page)
  const reloaded = await position(page)
  check(reloaded.chapter === beforeReload.chapter && reloaded.start === beforeReload.start, 'reload restores the precise phone passage')
  await jump(page, 0)
  await page.evaluate(() => __reader.turn(-1)); await settle(page)
  check(await page.evaluate(() => __reader.isOpen && __reader.visiblePages.right === 0), 'previous at the first page does not close the mobile book')
  await page.evaluate(() => __reader.goToLeaf(999999)); await settle(page)
  await page.evaluate(() => __reader.turn(1)); await settle(page)
  check(await page.evaluate(() => __reader.visiblePages.right === __reader.pagination.pages.length - 1), 'next at the last page does not reveal an empty leaf')
  await page.close()
  const english = await browser.newPage()
  english.on('pageerror', error => errors.push(error.message))
  await english.emulate({ userAgent: android, viewport: { width: 360, height: 800, deviceScaleFactor: 2, isMobile: true, hasTouch: true } })
  await english.goto(`${base}/?sample=alice&lang=en`); await ready(english); await jump(english, 3)
  check(await english.evaluate(() => __reader.phone && __reader.visiblePages.left === -1 && document.querySelectorAll('.text-page .w').length > 0), 'Android-sized English reader uses the same single-page model')
  await english.screenshot({ path: `${output}/english.png` })
  await english.close()
  const desktop = await browser.newPage()
  await desktop.setViewport({ width: 1440, height: 900 })
  await desktop.goto(`${base}/?sample=zh&lang=en`); await ready(desktop); await jump(desktop, 2)
  check(await desktop.evaluate(() => !__reader.phone && __reader.visiblePages.left === 3 && __reader.visiblePages.right === 4), 'desktop retains its two-page desk view')
  await desktop.screenshot({ path: `${output}/desktop.png` })
  await desktop.close()
  check(api.length === 0, 'mobile sample checks do not call production APIs')
  check(errors.length === 0, `no browser runtime errors: ${errors.join('; ')}`)
} finally { await browser.close() }
