"""Rebuild Wenkai subsets without changing glyphs/metrics. Requires fonttools[woff].

Uses the pinned Noto Serif SC Unicode partitions as a frequency-oriented starting
point, then includes every remaining original code point in bounded extra subsets.
The Noto font binaries are not used. Run from any directory after npm ci in web.
"""
from pathlib import Path
from concurrent.futures import ProcessPoolExecutor
import hashlib
import json
import re
import tempfile
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'node_modules/@fontsource/lxgw-wenkai/files/lxgw-wenkai-latin-500-normal.woff2'
OUTPUT = ROOT / 'src/assets/wenkai'


def ranges(points):
    result = []
    first = last = None
    for cp in sorted(points):
        if first is None:
            first = last = cp
        elif cp == last + 1:
            last = cp
        else:
            result.append(f'U+{first:X}' if first == last else f'U+{first:X}-{last:X}')
            first = last = cp
    if first is not None:
        result.append(f'U+{first:X}' if first == last else f'U+{first:X}-{last:X}')
    return ','.join(result)


def build(job):
    source, index, points = job
    font = TTFont(source, recalcTimestamp=False)
    original_metrics = {cp: font['hmtx'][name] for cp, name in font.getBestCmap().items() if cp in points}
    options = subset.Options()
    options.flavor = 'woff2'
    options.recalc_timestamp = False
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_legacy = True
    options.name_languages = ['*']
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    font.flavor = 'woff2'
    path = OUTPUT / f'lxgw-wenkai-500-{index:03}.woff2'
    font.save(path)
    check = TTFont(path)
    # Composite/layout closure can retain additional mapped glyphs. CSS exposes
    # only the assigned code points, so those extras cannot overlap other faces.
    assert set(points) <= set(check.getBestCmap())
    assert {cp: check['hmtx'][name] for cp, name in check.getBestCmap().items() if cp in points} == original_metrics
    return path.name, ranges(points), path.stat().st_size


def main():
    original = TTFont(SOURCE, recalcTimestamp=False)
    coverage = set(original.getBestCmap())
    # Keep Latin letters and punctuation together so Latin shaping is preserved.
    groups = [coverage & set(range(0x300))]
    used = set(groups[0])
    css = (ROOT / 'node_modules/@fontsource-variable/noto-serif-sc/index.css').read_text()
    for rule in re.findall(r'unicode-range:\s*([^;]+);', css):
        points = set()
        for value in rule.split(','):
            bounds = value.strip()[2:].split('-')
            points.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))
        points = points & coverage - used
        if points:
            groups.append(points)
            used.update(points)
    remaining = sorted(coverage - used)
    groups += [set(remaining[i:i + 256]) for i in range(0, len(remaining), 256)]
    assert set.union(*groups) == coverage
    assert sum(map(len, groups)) == len(coverage)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as temporary:
        source = str(Path(temporary) / 'source.ttf')
        original.flavor = None
        original.save(source)
        with ProcessPoolExecutor(max_workers=4) as pool:
            results = list(pool.map(build, [(source, i, points) for i, points in enumerate(groups)]))
    (OUTPUT / '500.css').write_text('/* Generated by scripts/subset-wenkai.py. Original font: SIL OFL 1.1. */\n' + '\n'.join(
        '@font-face {\n  font-family: "LXGW WenKai";\n  font-style: normal;\n  font-display: swap;\n  font-weight: 500;\n'
        f'  src: url("./{name}") format("woff2");\n  unicode-range: {unicode_range};\n}}\n'
        for name, unicode_range, _ in results))
    license_text = (ROOT / 'node_modules/@fontsource/lxgw-wenkai/LICENSE').read_text()
    (OUTPUT / 'LICENSE').write_text('\n'.join(line.rstrip() for line in license_text.splitlines()) + '\n')
    summary = {'sourceSha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(), 'sourceBytes': SOURCE.stat().st_size,
               'codepoints': len(coverage), 'subsets': len(results), 'subsetBytes': sum(size for _, _, size in results),
               'maxSubsetBytes': max(size for _, _, size in results)}
    (OUTPUT / 'manifest.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary), flush=True)


if __name__ == '__main__':
    main()
